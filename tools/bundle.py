"""Bundle the Csound MAL library into one readable include file."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

# Skip strings and comments before looking for real preprocessor directives.
# In particular, {{ ... }} holds the MAL source for the threading macros.
TOKENS = re.compile(
    r'/\*.*?\*/|\{\{.*?\}\}|"(?:\\.|[^"\\])*"|;[^\n]*|//[^\n]*'
    r'|(?P<include>^[ \t]*#include\b[^\n]*)',
    re.MULTILINE | re.DOTALL,
)
INCLUDE = re.compile(r'\s*#include\s+"([^"\n]+)"\s*(?:(?:;|//)[^\n]*)?')
SEMVER = re.compile(
    r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)"
    r"(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?"
    r"(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?"
)


def read_version(root=ROOT):
    version = (root / "VERSION").read_text(encoding="utf-8").strip()
    match = SEMVER.fullmatch(version)
    if match is None or any(part.isdigit() and len(part) > 1 and part.startswith("0")
                            for part in (match[4] or "").split(".")):
        raise ValueError("VERSION must contain one semantic version, such as 1.2.3 or 1.2.3-rc.1")
    return version


def artifact_name(version):
    return f"mal-{version}.inc"


class Bundler:
    def __init__(self, root):
        self.root = root.resolve()
        self.sources = set()

    def expand(self, source, stack=()):
        source = source.resolve()
        relative = source.relative_to(self.root).as_posix()
        if source in stack:
            chain = " -> ".join(p.relative_to(self.root).as_posix()
                                for p in (*stack, source))
            raise ValueError(f"Include cycle: {chain}")
        self.sources.add(source)
        text = source.read_text(encoding="utf-8")

        def replace(token):
            if token.lastgroup != "include":
                return token.group()
            directive = INCLUDE.fullmatch(token.group())
            if directive is None:
                raise ValueError(f"Unsupported include in {relative}: {token.group().strip()}")
            name = directive[1]
            candidates = (source.parent / name, self.root / name)
            for candidate in candidates:
                if candidate.is_file():
                    return self.expand(candidate, (*stack, source))
            raise ValueError(f"Missing include in {relative}: {name}")

        expanded = TOKENS.sub(replace, text)
        return f";; Begin {relative}\n{expanded.rstrip()}\n;; End {relative}\n"


def git_metadata(root):
    def git(*args):
        return subprocess.check_output(
            ["git", "-C", str(root), *args], stderr=subprocess.DEVNULL,
            text=True,
        ).strip()

    try:
        # A source archive inside another repository must not borrow its HEAD.
        if Path(git("rev-parse", "--show-toplevel")).resolve() != root.resolve():
            return "unknown", "unknown", "unknown"
        commit = git("rev-parse", "HEAD")
        date = git("show", "-s", "--format=%cI", "HEAD")
        state = "modified" if git("status", "--porcelain", "--untracked-files=all") else "clean"
        return commit, date, state
    except (OSError, subprocess.CalledProcessError):
        return "unknown", "unknown", "unknown"


def build(root, output):
    bundler = Bundler(root)
    source = bundler.expand(root / "src/main.orc")
    protected = bundler.sources | {root / "VERSION", root / "LICENSE", Path(__file__).resolve()}
    if output.resolve() in protected:
        raise ValueError("The output would overwrite a build input")
    version = read_version(root)
    commit, date, state = git_metadata(root)
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    license_text = (root / "LICENSE").read_text(encoding="utf-8").rstrip()
    header = f"""Csound MAL {version}
Author: Hlöðver Sigurðsson
Copyright (C) 2026 Hlöðver Sigurðsson.
SPDX-License-Identifier: MPL-2.0
Version: {version}
Commit: {commit}
Commit date: {date}
Source state: {state}
Source SHA-256: {digest}
Source: https://github.com/hlolli/csound-make-a-lisp
Requires: Csound 7
Generated by tools/bundle.py from src/main.orc. Edit the source files to rebuild.

This Source Code Form is subject to the terms of the Mozilla Public
License, v. 2.0. If a copy of the MPL was not distributed with this
file, You can obtain one at https://mozilla.org/MPL/2.0/.

{license_text}
"""
    comments = "\n".join(";; " + line if line else ";;" for line in header.splitlines())
    bundle = (comments + "\n\n#ifndef CSOUND_MAL_INCLUDED\n"
              "#define CSOUND_MAL_INCLUDED #1#\n\n" + source + "\n#endif\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(bundle)
    return len(bundler.sources)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="default: dist/mal-<VERSION>.inc")
    args = parser.parse_args()
    try:
        output = args.output or ROOT / "dist" / artifact_name(read_version())
        count = build(ROOT, output)
    except (OSError, ValueError) as error:
        print(f"Build failed: {error}", file=sys.stderr)
        return 1
    print(f"Built {output}: {count} source files, {output.stat().st_size:,} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
